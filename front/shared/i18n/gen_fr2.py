def translate(key, path, flat, path_trans):
    if path and f"{path}.{key}" in path_trans:
        return path_trans[f"{path}.{key}"]
    if key in path_trans:
        return path_trans[key]
    if key in flat:
        return flat[key]
    return None

def process(node, path=""):
    if isinstance(node, dict):
        result = {}
        for k, v in node.items():
            result[k] = process(v, f"{path}.{k}" if path else k)
        return result
    elif isinstance(node, str):
        t = translate(node, path, fr_flat, fr_path)
        return t if t is not None else node
    else:
        return node

